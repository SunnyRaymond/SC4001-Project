"""Build K=4 report tables from committed outputs; no model fitting or selection.

Accuracy and harm (%) are averaged equally over five seeds, then four domains.
All harm rates, including B1's, use B0 as the reference. This does not replace
the separate B1-referenced adapter analysis requested in README Section 7.8.
Run from any directory: python3 report/build_tables.py
"""
import csv
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "ViT-B-32-quickgelu"
DOMAINS = {"Art": "art", "Clipart": "clipart", "Product": "product", "Real World": "real_world"}


def read_csv(name):
    with (RESULTS / name).open(newline="") as stream:
        return list(csv.DictReader(stream))


def build():
    zs = read_csv("zero_shot_per_image.csv")
    assert [int(r["index"]) for r in zs] == list(range(len(zs)))
    labels = np.array([int(r["label"]) for r in zs])
    b0 = np.array([int(r["B0_pred"]) for r in zs])
    b1 = np.array([int(r["B1_pred"]) for r in zs])
    splits = np.load(ROOT / "splits" / "splits.npz")
    values = {m: {"acc": {}, "harm": {}} for m in ("B0", "B1")}
    for domain, slug in DOMAINS.items():
        accuracies, harms = [], []
        base = []
        for seed in range(5):
            test = splits[f"{slug}/seed{seed}/test"]
            ok0, ok1 = b0[test] == labels[test], b1[test] == labels[test]
            base.append(ok0.mean() * 100)
            accuracies.append(ok1.mean() * 100)
            harms.append((ok0 & ~ok1).mean() * 100)
        values["B0"]["acc"][domain] = float(np.mean(base))
        values["B0"]["harm"][domain] = 0.0
        values["B1"]["acc"][domain] = float(np.mean(accuracies))
        values["B1"]["harm"][domain] = float(np.mean(harms))

    # Preserve published K=4 rows and rounding; insert the missing B1 baseline.
    with (RESULTS / "main_table_k4.csv").open(newline="") as stream:
        rows = list(csv.reader(stream))[3:]
    for row in rows:
        method = row[0]
        if method == "B0":
            assert all(abs(values[method]["acc"][d] - float(v)) < 0.006
                       for d, v in zip(DOMAINS, row[1:5]))
        values[method] = {"acc": dict(zip(DOMAINS, map(float, row[1:5]))),
                          "harm": dict(zip(DOMAINS, map(float, row[5:9])))}
        values[method]["acc"]["Avg"] = float(row[9])
        values[method]["harm"]["Avg"] = float(row[10])
    for metric in ("acc", "harm"):
        values["B1"][metric]["Avg"] = float(np.mean(list(values["B1"][metric].values())))

    order = ["B0", "B1", "A1", "A1+G1", "A1+C1", "A2", "A2+G1", "A2+C1", "A4", "A4+G1", "A4+C1"]
    out = ROOT / "report" / "tables"
    out.mkdir(parents=True, exist_ok=True)
    for metric, suffix, caption in [
        ("acc", "accuracy", "K=4 test accuracy (percent)."),
        ("harm", "harm", "K=4 harm rate relative to B0 (percent of all test images)."),
    ]:
        lines = ["% Generated by report/build_tables.py; do not edit.", r"\begin{table}[htbp]",
                 r"\centering", r"\caption{" + caption + " Means over five seeds; Avg gives equal weight to each domain.}",
                 r"\label{tab:k4-" + suffix + "}", r"\begin{tabular}{lrrrrr}", r"\toprule",
                 r"Method & Art & Clipart & Product & Real World & Avg \\", r"\midrule"]
        for method in order:
            numbers = [f"{values[method][metric][d]:.2f}" for d in [*DOMAINS, "Avg"]]
            lines.append(" & ".join([method, *numbers]) + r" \\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
        target = out / f"k4-{suffix}.tex"
        target.write_text("\n".join(lines) + "\n")
        print(target.relative_to(ROOT))

    # Recompute the body table from per-seed outputs, before rounding.
    gating = pd.read_csv(RESULTS / "gating_summary.csv")
    assert len(gating) == 240 and not gating.duplicated(["method", "domain", "K", "seed"]).any()
    for method in ("A1", "A2", "A4"):
        for variant in ("ungated", "G1", "C1"):
            label = method if variant == "ungated" else f"{method}+{variant}"
            rows = gating[(gating.method == method) & (gating.K == 4)]
            for metric, col in [("acc", f"acc_{variant}"), ("harm", f"harm_{variant}")]:
                means = rows.groupby("domain")[col].mean() * 100
                values[label][metric] = {**means.to_dict(), "Avg": means.mean()}
    lines = ["% Generated by report/build_tables.py; do not edit.", r"\begin{table}[tbp]", r"\centering",
             r"\caption{K=4 accuracy / harm (percent). Harm uses all test images as its denominator and B0 as the reference. Domain means average five seeds; Avg weights domains equally. B1 uses no support labels.}",
             r"\label{tab:k4-main}", r"\setlength{\tabcolsep}{4pt}",
             r"\begin{tabular}{lrrrrr}", r"\toprule",
             r"Method & Art & Clipart & Product & Real World & Avg \\", r"\midrule"]
    for method in order:
        cells = [f"{values[method]['acc'][d]:.2f} / {values[method]['harm'][d]:.2f}"
                 for d in [*DOMAINS, "Avg"]]
        if method == "A2+C1":
            cells = [r"\textbf{" + c + "}" for c in cells]
        lines.append(" & ".join([method, *cells]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (out / "k4-main.tex").write_text("\n".join(lines) + "\n")

    def delta_cell(rows, a, b):
        diff = (rows[a] - rows[b]) * 100
        return f"${diff.mean():+.2f} \\pm {diff.std(ddof=1):.2f}$"

    header = ["% Generated by report/build_tables.py; do not edit.", r"\begin{table}[tbp]", r"\centering"]
    lines = header + [
        r"\caption{Paired accuracy differences (pp), mean $\pm$ sample SD over 80 domain--$K$--seed conditions per adapter. Positive values favour the first variant. Conditions share images, so SD is descriptive.}",
        r"\label{tab:gating-paired}", r"\begin{tabular}{lrrr}", r"\toprule",
        r"Adapter & G1 $-$ adapter & G1 $-$ C2 & C1 $-$ G1 \\", r"\midrule"]
    for method in ("A1", "A2", "A4"):
        rows = gating[gating.method == method]
        cells = [delta_cell(rows, a, b) for a, b in
                 [("acc_G1", "acc_ungated"), ("acc_G1", "acc_C2"), ("acc_C1", "acc_G1")]]
        lines.append(" & ".join([method, *cells]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (out / "gating-paired.tex").write_text("\n".join(lines) + "\n")

    vrf = pd.read_csv(RESULTS / "vrf_summary.csv")
    assert len(vrf) == 240 and not vrf.duplicated(["method", "domain", "K", "seed"]).any()
    paired = gating.merge(vrf, on=["method", "domain", "K", "seed"], suffixes=("_g", "_v"))
    assert np.allclose(paired.acc_C1_g, paired.acc_C1_v, atol=2e-6, rtol=0)
    lines = header + [
        r"\caption{VRF-style weighting versus fixed mixing and random-set weighting. Differences are mean $\pm$ sample SD (pp) over the same 80 conditions. W/T/L counts compare VRF with C1; absolute differences below 0.001 pp are ties to avoid overinterpreting rounded CSV values.}",
        r"\label{tab:vrf-paired}", r"\begin{tabular}{lrrr}", r"\toprule",
        r"Adapter & VRF $-$ C1 & W/T/L & VRF $-$ V0 \\", r"\midrule"]
    for method in ("A1", "A2", "A4"):
        rows = vrf[vrf.method == method]
        diff = (rows.acc_VRF - rows.acc_C1) * 100
        counts = f"{(diff >= 0.001).sum()}/{(diff.abs() < 0.001).sum()}/{(diff <= -0.001).sum()}"
        lines.append(" & ".join([method, delta_cell(rows, "acc_VRF", "acc_C1"), counts,
                                 delta_cell(rows, "acc_VRF", "acc_V0")]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (out / "vrf-paired.tex").write_text("\n".join(lines) + "\n")
    print("report/tables/{k4-main,gating-paired,vrf-paired}.tex")


if __name__ == "__main__":
    build()
